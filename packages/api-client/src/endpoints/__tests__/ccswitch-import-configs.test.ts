import { beforeEach, describe, expect, test, vi } from "vitest";
import { apiClient } from "../../client/client";
import {
  ccSwitchImportConfigsApi,
  normalizeCcSwitchImportConfigs,
} from "@code-proxy/api-client/endpoints/ccswitch-import-configs";

vi.mock("../../client/client", () => ({
  apiClient: {
    get: vi.fn(),
    put: vi.fn(),
  },
}));

const mockedApiGet = vi.mocked(apiClient.get);
const mockedApiPut = vi.mocked(apiClient.put);

const codexRow = {
  id: "codex-deepseek",
  "client-type": "codex",
  "provider-name": "Pro pool + DeepSeek",
  "default-model": "gpt-5.5",
  "model-mappings": [
    { "request-model": "gpt-5.5", "target-model": "gpt-5.5", "context-window": 272000 },
    { "request-model": "deepseek-v4-flash", "target-model": "deepseek-chat" },
  ],
  "allowed-channel-groups": ["pro"],
  "route-path": "/pro/cs_deepseek",
  "endpoint-path": "/v1",
  "usage-auto-interval": 30,
  "codex-context-window": 400000,
  // Generated by the backend on GET; only each model's default reasoning effort is used.
  "codex-model-catalog-filename": "cc-switch-model-catalog.json",
  "codex-model-catalog": {
    models: [
      {
        model: "gpt-5.5",
        display_name: "gpt-5.5",
        default_reasoning_level: "medium",
        supported_reasoning_levels: ["low", "medium", "high", "xhigh"],
      },
      { slug: "deepseek-v4-flash", defaultReasoningLevel: "low" },
    ],
  },
};

describe("ccSwitchImportConfigsApi", () => {
  beforeEach(() => {
    mockedApiGet.mockReset();
    mockedApiPut.mockReset();
    mockedApiPut.mockResolvedValue(undefined);
  });

  test("serializes model mappings, alias request names included, without dead fields", async () => {
    await ccSwitchImportConfigsApi.replace([
      {
        id: "kimi-code",
        clientType: "claude",
        providerName: "Kimi code",
        note: "kimicode",
        defaultModel: "kimi-k2.5",
        allowedChannelGroups: ["kimicode"],
        routePath: "/kimicode/cs_kimi",
        endpointPath: "",
        usageAutoInterval: 30,
        modelMappings: [
          { role: "main", requestModel: "kimi-k2.5", targetModel: "kimi-k2.5" },
          { role: "haiku", requestModel: "claude-3-5-haiku", targetModel: "kimi-k2.5" },
        ],
      },
    ]);

    expect(mockedApiPut).toHaveBeenCalledWith("/ccswitch-import-configs", [
      {
        id: "kimi-code",
        "client-type": "claude",
        "provider-name": "Kimi code",
        note: "kimicode",
        "default-model": "kimi-k2.5",
        "model-mappings": [
          { role: "main", "request-model": "kimi-k2.5", "target-model": "kimi-k2.5" },
          {
            role: "haiku",
            "request-model": "claude-3-5-haiku",
            "target-model": "kimi-k2.5",
          },
        ],
        "allowed-channel-groups": ["kimicode"],
        "route-path": "/kimicode/cs_kimi",
        "endpoint-path": "",
        "usage-auto-interval": 30,
      },
    ]);
  });

  test("never sends the Codex catalog back: the backend regenerates it", async () => {
    const [config] = normalizeCcSwitchImportConfigs([codexRow]);
    await ccSwitchImportConfigsApi.replace([config!]);

    const [row] = mockedApiPut.mock.calls[0]![1] as Array<Record<string, unknown>>;
    expect(Object.keys(row!)).not.toContain("codex-model-catalog");
    expect(Object.keys(row!)).not.toContain("codex-model-catalog-filename");
    // Per-mapping windows from earlier editors go back exactly as they came.
    expect(row!["model-mappings"]).toEqual([
      { "request-model": "gpt-5.5", "target-model": "gpt-5.5", "context-window": 272000 },
      { "request-model": "deepseek-v4-flash", "target-model": "deepseek-chat" },
    ]);
  });

  test("sends codex-context-window only to a backend that reports the capability", async () => {
    const configs = normalizeCcSwitchImportConfigs([
      codexRow,
      { id: "oc", "client-type": "opencode", "default-model": "kimi-k2" },
    ]);

    await ccSwitchImportConfigsApi.replace(configs);
    const legacyRows = mockedApiPut.mock.calls[0]![1] as Array<Record<string, unknown>>;
    for (const row of legacyRows) expect(Object.keys(row)).not.toContain("codex-context-window");

    await ccSwitchImportConfigsApi.replace(configs, { codexContextWindow: true });
    const rows = mockedApiPut.mock.calls[1]![1] as Array<Record<string, unknown>>;
    expect(rows.map((row) => row["codex-context-window"])).toEqual([400000, 0]);
  });

  test("snapshot reports the backend's client-types, or null when it predates them", async () => {
    mockedApiGet.mockResolvedValueOnce({
      "ccswitch-import-configs": [codexRow],
      "client-types": ["claude", "codex", "gemini", "opencode", "openclaw", "hermes", "pi"],
      capabilities: { "codex-context-window": true },
    });
    const current = await ccSwitchImportConfigsApi.snapshot();
    expect(current.capabilities).toEqual({ codexContextWindow: true });
    expect(current.configs.map((config) => config.id)).toEqual(["codex-deepseek"]);
    expect(current.clientTypes).toEqual([
      "claude",
      "codex",
      "gemini",
      "opencode",
      "openclaw",
      "hermes",
    ]);

    mockedApiGet.mockResolvedValueOnce({ "ccswitch-import-configs": [codexRow] });
    const legacy = await ccSwitchImportConfigsApi.snapshot();
    expect(legacy.clientTypes).toBeNull();
    expect(legacy.capabilities).toEqual({ codexContextWindow: false });
  });
});

describe("normalizeCcSwitchImportConfigs", () => {
  test("keeps each Codex model's default reasoning effort from the backend catalog", () => {
    const [config] = normalizeCcSwitchImportConfigs([codexRow]);
    expect(config).toMatchObject({
      clientType: "codex",
      defaultModel: "gpt-5.5",
      modelMappings: [
        { requestModel: "gpt-5.5", targetModel: "gpt-5.5", contextWindow: 272000 },
        { requestModel: "deepseek-v4-flash", targetModel: "deepseek-chat" },
      ],
      codexContextWindow: 400000,
      codexReasoningEfforts: { "gpt-5.5": "medium", "deepseek-v4-flash": "low" },
    });
    expect(config).not.toHaveProperty("codexModelCatalog");
    // 0 means "not set", which is what the backend returns for every non-Codex row.
    const [unset] = normalizeCcSwitchImportConfigs([{ ...codexRow, "codex-context-window": 0 }]);
    expect(unset).not.toHaveProperty("codexContextWindow");
  });

  test("reads the efforts a cached row carries directly", () => {
    const [config] = normalizeCcSwitchImportConfigs([
      {
        ...codexRow,
        "codex-model-catalog": undefined,
        codexReasoningEfforts: { "gpt-5.5": "xhigh" },
      },
    ]);
    expect(config?.codexReasoningEfforts).toEqual({ "gpt-5.5": "xhigh" });
  });

  test("accepts OpenCode, OpenClaw and Hermes rows and ignores a stored api-key-field", () => {
    const configs = normalizeCcSwitchImportConfigs([
      { id: "a", "client-type": "OpenCode", "default-model": "kimi-k2" },
      { id: "b", "client-type": "openclaw", "default-model": "kimi-k2" },
      { id: "c", "client-type": "hermes", "default-model": "kimi-k2" },
      {
        id: "d",
        "client-type": "claude",
        "default-model": "kimi-k2",
        "api-key-field": "ANTHROPIC_API_KEY",
      },
      { id: "e", "client-type": "grokbuild", "default-model": "grok-4.5" },
    ]);
    expect(configs.map((config) => [config.id, config.clientType])).toEqual([
      ["a", "opencode"],
      ["b", "openclaw"],
      ["c", "hermes"],
      ["d", "claude"],
    ]);
    expect(configs[3]).not.toHaveProperty("apiKeyField");
  });
});
