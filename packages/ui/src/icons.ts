import { createElement, type FunctionComponent, type SVGProps } from "react";
import { Icon } from "satin-ui/react";

export interface SatinIconProps extends Omit<SVGProps<SVGSVGElement>, "name" | "width" | "height"> {
  size?: number | string;
  strokeWidth?: number | string;
}

export type SatinIconComponent = FunctionComponent<SatinIconProps> & {
  displayName?: string;
  /** 对应的原生 Satin Solar 图标名（位于 satin-ui/src/foundation/icons.js）。 */
  satinName?: string;
};

/**
 * 基于 `satin-ui/react` `<Icon />`（Satin Solar 双色调图标体系 `.sn-ic` + `.sn-ic-d`）的图标工厂。
 *
 * - 统一渲染原生 Satin 1.5px 圆头矢量路径，忽略旧调用方传入的 `strokeWidth` 差异，保证全站线宽一致；
 * - 保留语义 `displayName`，让 `theme/hues.ts`（`hueForIcon` / `iconHueClass` / `DialogIcon`）继续按语义稳定取色；
 * - 每个导出均标注 PURE，确保 Vite/Rollup 按需 tree-shaking。
 */
function makeSatinIcon(satinName: string, displayName: string): SatinIconComponent {
  const SatinIcon: SatinIconComponent = ({ size = 16, strokeWidth: _strokeWidth, ...rest }) =>
    createElement(Icon, {
      ...rest,
      name: satinName,
      size: typeof size === "string" ? Number(size) || 16 : size,
    });
  SatinIcon.displayName = displayName;
  SatinIcon.satinName = satinName;
  return SatinIcon;
}

